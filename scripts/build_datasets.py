"""Generate the corpora, then write ``data/MANIFEST.json`` and the committed samples.

One command behind every number in this repo that needs more than a seed:

* **generates** the ISO 8583 corpus (120,120 messages over 50,960 lifecycles) and the
  wallet utterance set (200,000 labelled cases)
* **measures** the four downloaded files rather than trusting their names: row counts
  are counted, not quoted
* **records** each one in the manifest with its row count, byte size and sha256, and
  writes the first 200 rows into ``data/samples/`` - which is committed, so the shape of
  a 128 MB file is visible in the repo without downloading anything
* **enforces** the size policy: every dataset has to hold between 50,000 and 1,000,000
  rows. The floor is what makes a rate meaningful; the ceiling is what keeps a pure
  standard-library pass over the file down to seconds.

``make data`` runs the fetch and then this.
"""

from __future__ import annotations

import json
import pathlib
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from projects.p01_switchboard import corpus  # noqa: E402
from projects.p02_policy_bench import cardbook, loanbook  # noqa: E402
from projects.p03_guardian import generator  # noqa: E402
from projects.p04_spec_to_wire import bank as wire_bank  # noqa: E402
from projects.p05_policy_from_prose import bank as policy_bank  # noqa: E402
from shared import datasets  # noqa: E402


def generated_corpora(rebuild: bool) -> list[tuple[str, pathlib.Path, int, str, str, str]]:
    out = []

    if rebuild or not corpus.path().is_file():
        print("generating the ISO 8583 corpus")
        built = corpus.build()
        rows = int(built["messages"])
    else:
        rows = datasets.count_rows(corpus.path(), header=False)
    out.append(
        (
            corpus.KEY,
            corpus.path(),
            rows,
            "generated by projects/p01_switchboard/corpus.py",
            "120,120 messages over 50,960 lifecycles, every one packed and re-parsed by "
            "the product's own codec before it was written. No public corpus of real card "
            "traffic exists, and for PCI reasons there will not be one.",
            "cohort",
        )
    )

    if rebuild or not generator.path().is_file():
        print("generating the wallet utterance set")
        built = generator.build()
        rows = int(built["cases"])
    else:
        rows = datasets.count_rows(generator.path(), header=False)
    out.append(
        (
            generator.KEY,
            generator.path(),
            rows,
            "generated by projects/p03_guardian/generator.py",
            "200,000 labelled utterances. The gold label comes from how each sentence was "
            "composed, and the spellings are the ones attested in 37,220 real Roman Urdu "
            "sentences.",
            "cohort",
        )
    )
    if rebuild or not wire_bank.path().is_file():
        print("generating the wire task bank")
        built = wire_bank.build()
        rows = int(built["tasks"])
    else:
        rows = datasets.count_rows(wire_bank.path(), header=False)
    out.append(
        (
            wire_bank.KEY,
            wire_bank.path(),
            rows,
            "generated by projects/p04_spec_to_wire/bank.py",
            "60,000 wire tasks drawn from the ISO 8583 corpus, 15,000 of each family. "
            "The answers come from the corpus, so project 01's codec can be scored on "
            "every one of them rather than on the 29 the model is asked.",
            "cohort",
        )
    )

    if rebuild or not policy_bank.path().is_file():
        print("generating the policy bank")
        built = policy_bank.build()
        rows = int(built["policies"])
    else:
        rows = datasets.count_rows(policy_bank.path(), header=False)
    out.append(
        (
            policy_bank.KEY,
            policy_bank.path(),
            rows,
            "generated by projects/p05_policy_from_prose/bank.py",
            "60,000 credit policies sampled from the DSL grammar, each one written out "
            "in prose and in policy text. Doubles as a grammar fuzzer: every one is "
            "compiled, reprinted and compiled again.",
            "cohort",
        )
    )
    return out


def raw_files() -> list[tuple[str, pathlib.Path, int, str, str, str]]:
    return [
        (
            loanbook.KEY,
            loanbook.path(),
            -1,
            loanbook.SOURCE,
            "Real loan applications with the outcome that happened: 29,653 defaults, a "
            "base rate of 11.61%. The one file here whose backtest is not circular.",
            "cohort",
        ),
        (
            cardbook.KEY_APPLICATIONS,
            cardbook.applications_path(),
            -1,
            cardbook.SOURCE,
            "Real card applications. Only 8.3% join to a repayment history, so the whole "
            "book is scored with every outcome figure withheld.",
            "cohort",
        ),
        (
            cardbook.KEY_RECORDS,
            cardbook.records_path(),
            -1,
            cardbook.SOURCE,
            "Monthly repayment status per account. Two definitions of bad - ever 30+ and "
            "ever 60+ days past due - disagree by nearly seven times on the same rows. "
            "A lookup table, not a cohort: nothing reports a rate over these rows.",
            "lookup",
        ),
    ]


def main() -> None:
    rebuild = "--rebuild" in sys.argv
    started = time.perf_counter()
    entries: list[tuple[str, pathlib.Path, int, str, str, str]] = []
    entries += generated_corpora(rebuild)
    entries += raw_files()

    print()
    print(f"{'dataset':34} {'rows':>10} {'size':>12}  {'role':8} policy")
    problems: list[str] = []
    for key, path, rows, source, note, role in entries:
        if not path.is_file():
            problems.append(f"{key}: {path} is missing. Run: make fetch")
            print(f"{key:34} {'-':>10} {'-':>12}  {role:8} missing")
            continue
        counted = rows if rows >= 0 else datasets.count_rows(path)
        entry = datasets.record(key, path, rows=counted, source=source, note=note, role=role)
        inside = "ok" if entry["within_the_size_policy"] else "OUTSIDE 50,000-1,000,000"
        print(f"{key:34} {counted:>10,} {entry['bytes']:>12,}  {role:8} {inside}")
        if not entry["within_the_size_policy"]:
            problems.append(f"{key}: {counted:,} rows is outside the size policy")

    print()
    print(f"manifest: {datasets.MANIFEST.relative_to(ROOT)}")
    print(f"samples:  {datasets.SAMPLES.relative_to(ROOT)} (committed)")
    print(f"took {time.perf_counter() - started:.1f}s")
    if problems:
        print()
        for problem in problems:
            print(f"  ! {problem}")
        raise SystemExit(1)
    print(json.dumps({"datasets": len(entries)}))


if __name__ == "__main__":
    main()
