"""Replace the README's Input / Output blocks with what `demo.py` actually prints.

    uv run python scripts/build_readme_io.py

The root README shows what each project does by printing real input and real output. That
is the right content and it was pasted in by hand, which means it went stale the moment a
cohort grew from 5,000 rows to 50,000: the block still showed a Gini of 0.284 and a
region gap of 39.0% that nothing in the repo produced any more.

So the blocks between the ``io`` markers are generated by running the demo and capturing
its output, exactly as a reader would see it. CI fails if the committed copy differs,
which makes a stale published figure a build failure rather than a thing somebody notices
months later.

The prose and the headings around the markers are written by hand and never touched.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

#: Which demo to run for each marked block, and how much of its output to keep. Trimming
#: is by section heading rather than by line number: a line count would silently take the
#: wrong lines the next time a demo printed one more row.
BLOCKS = {
    "01": {
        "demo": "1",
        "start": "  INPUT   scenario",
        "stop": None,
    },
    "02": {
        "demo": "2",
        "start": "  INPUT   three policy files",
        "stop": None,
    },
    "03": {
        "demo": "3",
        "start": "  INPUT   amounts as people actually say them",
        "stop": None,
    },
}

RULE = "=" * 78


def run_demo(choice: str) -> str:
    result = subprocess.run(
        [sys.executable, str(ROOT / "demo.py"), choice],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(f"demo {choice} failed:\n{result.stderr[-2000:]}")
    return result.stdout


def trim(output: str, start: str, stop: str | None) -> str:
    lines = output.replace("\r\n", "\n").split("\n")
    try:
        first = next(index for index, line in enumerate(lines) if line.startswith(start))
    except StopIteration as exc:
        raise SystemExit(f"could not find {start!r} in the demo output") from exc
    last = len(lines)
    for index in range(first, len(lines)):
        if lines[index].startswith(RULE[:20]) or lines[index].strip() == "done":
            last = index
            break
    kept = lines[first:last]
    while kept and not kept[-1].strip():
        kept.pop()
    return "\n".join(kept)


def main() -> int:
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    changed = False

    for key, spec in BLOCKS.items():
        start_marker = f"<!-- io:{key}:start -->"
        end_marker = f"<!-- io:{key}:end -->"
        if start_marker not in text:
            print(f"{key}: no markers in README.md, skipped")
            continue
        body = trim(run_demo(spec["demo"]), spec["start"], spec["stop"])
        block = f"{start_marker}\n```\n{body}\n```\n{end_marker}"
        pattern = re.compile(re.escape(start_marker) + r".*?" + re.escape(end_marker), re.DOTALL)
        # A default argument, not a closure: ruff is right that a lambda capturing the
        # loop variable would substitute the last block into every marker if this ever
        # became lazy.
        new_text = pattern.sub(lambda _match, replacement=block: replacement, text, count=1)
        if new_text != text:
            changed = True
        text = new_text
        print(f"{key}: {len(body.splitlines())} lines")

    readme.write_text(text, encoding="utf-8", newline="\n")
    print("wrote README.md" if changed else "README.md unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
